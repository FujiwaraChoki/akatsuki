// Generates src/components/iconData.ts from the shared stroke icon set (ARCHITECTURE design spec §2.11): the
// desktop's apps/desktop/assets/icons/*.svg (the single source until it moves to packages/ui/icons) plus the few
// mobile-only glyphs in apps/mobile/assets/icons. Run: `node scripts/icons.mjs` (test/icons.test.ts checks it).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const SOURCES = [join(here, "../../desktop/assets/icons"), join(here, "../assets/icons")];
export const OUT = join(here, "../src/components/_generated/iconData.ts");

const ELEMENTS = new Set(["path", "rect", "circle", "line", "polyline", "polygon", "ellipse"]);
const ATTRS = new Set([
  "d",
  "x",
  "y",
  "width",
  "height",
  "rx",
  "ry",
  "cx",
  "cy",
  "r",
  "x1",
  "y1",
  "x2",
  "y2",
  "points",
  "fill",
]);

export function parseSvg(svg) {
  const out = [];
  for (const m of svg.matchAll(/<(\w+)\b([^>]*?)\/?>/g)) {
    const tag = m[1];
    if (!ELEMENTS.has(tag)) continue;
    const attrs = {};
    for (const a of m[2].matchAll(/([\w-]+)="([^"]*)"/g)) if (ATTRS.has(a[1])) attrs[a[1]] = a[2];
    out.push([tag, attrs]);
  }
  return out;
}

export function generate() {
  const icons = {};
  for (const dir of SOURCES)
    for (const f of readdirSync(dir)
      .filter((x) => x.endsWith(".svg"))
      .sort())
      icons[f.slice(0, -4)] = parseSvg(readFileSync(join(dir, f), "utf8"));
  const names = Object.keys(icons).sort();
  const body = names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(icons[n])},`).join("\n");
  return `// Generated by scripts/icons.mjs from apps/desktop/assets/icons and apps/mobile/assets/icons. Do not edit.
export type IconElement = [tag: string, attrs: Record<string, string>];

export const ICON_DATA = {
${body}
} satisfies Record<string, IconElement[]>;

export type IconName = keyof typeof ICON_DATA;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, generate());
  process.stdout.write(`wrote ${OUT}\n`);
}
