// Pure generators: tokens.json -> CSS variables, TypeScript constants, Rust constants.
// No file system access here, so the unit tests can call every function directly.

export type Hex = `#${string}`;

export interface Palette {
  accent: Hex;
  /** Accent-coloured text and thin strokes: the accent where it reads (light), lifted toward the foreground where
   *  the accent is too dark to read (dark). Fills keep `accent`. */
  accentText: Hex;
  background: Hex;
  foreground: Hex;
}

/** Palette keys, in output order. */
export const PALETTE_KEYS = ["accent", "accentText", "background", "foreground"] as const;

export type FontRole = "serif" | "sans" | "mono";

export interface FontDef {
  family: string;
  fallback: string[];
  weights: number[];
  files: Record<string, string>;
}

export interface TextStyle {
  font: FontRole;
  size: number;
  sizeWide?: number;
  lineHeight: number;
  tracking: number;
  weight: number;
  uppercase?: boolean;
}

export interface Tokens {
  color: { light: Palette; dark: Palette };
  opacity: { foreground: Record<string, number>; accent: Record<string, number> };
  space: { base: number; scale: Record<string, number> };
  radius: Record<string, number>;
  font: Record<FontRole, FontDef>;
  text: { app: Record<string, TextStyle>; brand: Record<string, TextStyle> };
  motion: {
    duration: Record<string, number>;
    easing: Record<string, [number, number, number, number]>;
    orb: {
      blur: number;
      opacity: number;
      floatSeconds: number[];
      morphSeconds: number[];
      pulseSeconds: number;
    };
  };
  layout: Record<string, number>;
  effect: Record<string, number>;
}

export const GENERATED_HEADER =
  "Generated by packages/tokens/scripts/build.ts from packages/tokens/tokens.json. Do not edit.";

// ───────────── validation ─────────────

const HEX_RE = /^#[0-9a-fA-F]{6}$/;
const KEY_RE = /^[A-Za-z0-9_]+$/;

export function validateTokens(input: unknown): Tokens {
  const t = input as Tokens;
  const fail = (msg: string): never => {
    throw new Error(`tokens.json: ${msg}`);
  };
  if (!t || typeof t !== "object") fail("not an object");
  for (const mode of ["light", "dark"] as const) {
    const p = t.color?.[mode];
    if (!p) fail(`color.${mode} missing`);
    for (const k of PALETTE_KEYS) {
      if (typeof p[k] !== "string" || !HEX_RE.test(p[k])) fail(`color.${mode}.${k} must be #RRGGBB`);
    }
  }
  for (const group of ["foreground", "accent"] as const) {
    for (const [k, v] of Object.entries(t.opacity?.[group] ?? fail(`opacity.${group} missing`))) {
      if (!KEY_RE.test(k)) fail(`opacity.${group}.${k}: bad key`);
      if (typeof v !== "number" || v < 0 || v > 1) fail(`opacity.${group}.${k} must be in [0, 1]`);
    }
  }
  if (t.space?.base !== 8) fail("space.base must be 8 (8px grid)");
  for (const [k, v] of Object.entries(t.space.scale)) {
    if (!KEY_RE.test(k)) fail(`space.scale.${k}: bad key`);
    if (typeof v !== "number" || v < 0 || v % 4 !== 0) fail(`space.scale.${k} must be a multiple of 4`);
  }
  for (const role of ["serif", "sans", "mono"] as const) {
    const f = t.font?.[role];
    if (!f || typeof f.family !== "string") fail(`font.${role}.family missing`);
  }
  if (t.font.serif.weights.some((w) => w !== 400)) fail("Instrument Serif is single weight 400");
  for (const scale of ["app", "brand"] as const) {
    for (const [k, s] of Object.entries(t.text?.[scale] ?? fail(`text.${scale} missing`))) {
      if (k.startsWith("$")) continue;
      if (!KEY_RE.test(k)) fail(`text.${scale}.${k}: bad key`);
      if (!(s.font in t.font)) fail(`text.${scale}.${k}.font unknown`);
      if (s.font === "serif" && s.weight !== 400) fail(`text.${scale}.${k}: serif has no bold`);
    }
  }
  return t;
}

// ───────────── helpers ─────────────

export function hexToRgb(hex: string): [number, number, number] {
  if (!HEX_RE.test(hex)) throw new Error(`bad hex colour: ${hex}`);
  const n = Number.parseInt(hex.slice(1), 16);
  return [(n >> 16) & 0xff, (n >> 8) & 0xff, n & 0xff];
}

/** "0_5" -> "0-5", "borderHover" -> "border-hover" */
export function kebab(key: string): string {
  return key
    .replace(/_/g, "-")
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .toLowerCase();
}

/** "borderHover" -> "BORDER_HOVER", "0_5" -> "0_5" */
export function screamingSnake(key: string): string {
  return key.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();
}

function textEntries(t: Tokens, scale: "app" | "brand"): [string, TextStyle][] {
  return Object.entries(t.text[scale]).filter(([k]) => !k.startsWith("$"));
}

function fontStack(f: FontDef): string {
  const quote = (name: string) => (/[\s]/.test(name) && !name.startsWith("-") ? `"${name}"` : name);
  return [f.family, ...f.fallback].map(quote).join(", ");
}

function num(n: number): string {
  // Stable formatting with no trailing zeros; integers stay integers.
  return Number.isInteger(n) ? String(n) : String(Number(n.toFixed(4)));
}

function cubic(e: [number, number, number, number]): string {
  return `cubic-bezier(${e.map(num).join(", ")})`;
}

// ───────────── CSS ─────────────

function paletteVars(p: Palette): string[] {
  const out: string[] = [];
  for (const k of PALETTE_KEYS) {
    out.push(`--${kebab(k)}: ${p[k].toUpperCase()};`);
    out.push(`--${kebab(k)}-rgb: ${hexToRgb(p[k]).join(" ")};`);
  }
  return out;
}

function derivedColorVars(t: Tokens): string[] {
  const out: string[] = [];
  for (const [k, v] of Object.entries(t.opacity.foreground)) {
    out.push(`--fg-${kebab(k)}: rgb(var(--foreground-rgb) / ${num(v)});`);
  }
  for (const [k, v] of Object.entries(t.opacity.accent)) {
    out.push(`--accent-${kebab(k)}: rgb(var(--accent-rgb) / ${num(v)});`);
  }
  out.push(
    `--glow: 0 0 ${num(t.effect.glowBlur ?? 30)}px rgb(var(--accent-rgb) / ${num(t.effect.glowOpacity ?? 0.4)});`,
  );
  return out;
}

function staticVars(t: Tokens): string[] {
  const out: string[] = [];
  for (const [k, v] of Object.entries(t.opacity.foreground)) out.push(`--opacity-fg-${kebab(k)}: ${num(v)};`);
  for (const [k, v] of Object.entries(t.opacity.accent)) out.push(`--opacity-accent-${kebab(k)}: ${num(v)};`);
  for (const [k, v] of Object.entries(t.space.scale)) out.push(`--space-${kebab(k)}: ${v}px;`);
  for (const [k, v] of Object.entries(t.radius)) out.push(`--radius-${kebab(k)}: ${v}px;`);
  for (const role of ["serif", "sans", "mono"] as const)
    out.push(`--font-${role}: ${fontStack(t.font[role])};`);
  for (const scale of ["app", "brand"] as const) {
    for (const [k, s] of textEntries(t, scale)) {
      const p = `--text-${scale}-${kebab(k)}`;
      out.push(`${p}-font: var(--font-${s.font});`);
      out.push(`${p}-size: ${num(s.size)}px;`);
      if (s.sizeWide !== undefined) out.push(`${p}-size-wide: ${num(s.sizeWide)}px;`);
      out.push(`${p}-line-height: ${num(s.lineHeight)};`);
      out.push(`${p}-tracking: ${num(s.tracking)}em;`);
      out.push(`${p}-weight: ${s.weight};`);
    }
  }
  for (const [k, v] of Object.entries(t.motion.duration)) out.push(`--duration-${kebab(k)}: ${v}ms;`);
  for (const [k, v] of Object.entries(t.motion.easing)) out.push(`--ease-${kebab(k)}: ${cubic(v)};`);
  out.push(`--orb-blur: ${num(t.motion.orb.blur)}px;`);
  out.push(`--orb-opacity: ${num(t.motion.orb.opacity)};`);
  for (const [k, v] of Object.entries(t.layout)) out.push(`--layout-${kebab(k)}: ${v}px;`);
  out.push(`--card-blur: ${num(t.effect.cardBlur ?? 20)}px;`);
  return out;
}

const block = (selector: string, lines: string[], indent = "") =>
  `${indent}${selector} {\n${lines.map((l) => `${indent}  ${l}`).join("\n")}\n${indent}}`;

/**
 * Light is the default. Dark applies when the OS prefers it, unless the page forces
 * `data-theme="light"`; `data-theme="dark"` forces dark regardless of the OS.
 */
export function toCss(t: Tokens): string {
  const light = [...paletteVars(t.color.light), "color-scheme: light;"];
  const dark = [...paletteVars(t.color.dark), "color-scheme: dark;"];
  const parts = [
    `/* ${GENERATED_HEADER} */`,
    block(":root", [...staticVars(t), ...derivedColorVars(t)]),
    block(':root,\n[data-theme="light"]', light),
    `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme="light"])', dark, "  ")}\n}`,
    block('[data-theme="dark"]', dark),
    // The derived colours must be re-declared where the palette changes, because custom
    // properties referencing other custom properties resolve on the element that declares them.
    block('[data-theme="light"],\n[data-theme="dark"]', derivedColorVars(t)),
    `@media (prefers-reduced-motion: reduce) {\n${block(":root", ["--duration-instant: 0ms;", "--duration-fast: 0ms;", "--duration-normal: 0ms;", "--duration-slow: 0ms;", "--duration-stagger: 0ms;"], "  ")}\n}`,
  ];
  return `${parts.join("\n\n")}\n`;
}

/** @font-face rules for the bundled fonts; `fontsUrl` is relative to the CSS file. */
export function toFontFaceCss(t: Tokens, fontsUrl = "../fonts"): string {
  const rules: string[] = [`/* ${GENERATED_HEADER} */`];
  for (const role of ["serif", "sans", "mono"] as const) {
    const f = t.font[role];
    for (const [variant, file] of Object.entries(f.files)) {
      const weight = Number.parseInt(variant, 10);
      const style = variant.endsWith("italic") ? "italic" : "normal";
      rules.push(
        block("@font-face", [
          `font-family: "${f.family}";`,
          // WOFF2 (about a third of the TTF, compressed with woff2_compress, D-409) first; TTF for the rest.
          `src: url("${fontsUrl}/${file.replace(/\.ttf$/, ".woff2")}") format("woff2"), url("${fontsUrl}/${file}") format("truetype");`,
          `font-weight: ${weight};`,
          `font-style: ${style};`,
          "font-display: swap;",
        ]),
      );
    }
  }
  return `${rules.join("\n\n")}\n`;
}

// ───────────── TypeScript ─────────────

export function toTs(t: Tokens): string {
  const rgb = (p: Palette) =>
    Object.fromEntries(PALETTE_KEYS.map((k) => [k, hexToRgb(p[k])])) as Record<
      keyof Palette,
      [number, number, number]
    >;
  const fonts = Object.fromEntries(
    (["serif", "sans", "mono"] as const).map((r) => [
      r,
      {
        family: t.font[r].family,
        stack: fontStack(t.font[r]),
        weights: t.font[r].weights,
        files: t.font[r].files,
      },
    ]),
  );
  const strip = (o: Record<string, TextStyle>) =>
    Object.fromEntries(Object.entries(o).filter(([k]) => !k.startsWith("$")));
  const data = {
    color: {
      light: { ...upper(t.color.light), rgb: rgb(t.color.light) },
      dark: { ...upper(t.color.dark), rgb: rgb(t.color.dark) },
    },
    opacity: t.opacity,
    space: t.space.scale,
    radius: t.radius,
    font: fonts,
    text: { app: strip(t.text.app), brand: strip(t.text.brand) },
    motion: t.motion,
    layout: t.layout,
    effect: t.effect,
  };
  const json = JSON.stringify(data, null, 2);
  return `// ${GENERATED_HEADER}

export const tokens = ${json} as const;

export type Tokens = typeof tokens;
export type ThemeMode = "light" | "dark";
export type ColorName = "accent" | "accentText" | "background" | "foreground";
export type FontRole = keyof Tokens["font"];
export type SpaceKey = keyof Tokens["space"];
export type RadiusKey = keyof Tokens["radius"];
export type AppTextStyle = keyof Tokens["text"]["app"];
export type BrandTextStyle = keyof Tokens["text"]["brand"];
export type ForegroundOpacity = keyof Tokens["opacity"]["foreground"];
export type AccentOpacity = keyof Tokens["opacity"]["accent"];

export const { color, opacity, space, radius, font, text, motion, layout, effect } = tokens;

/** rgba() string for a palette colour at one of the opacity steps, for React Native styles. */
export function rgba(mode: ThemeMode, name: ColorName, alpha: number): string {
  const [r, g, b] = tokens.color[mode].rgb[name];
  return \`rgba(\${r}, \${g}, \${b}, \${alpha})\`;
}

/** Foreground at a named opacity step, e.g. fg("dark", "muted"). */
export function fg(mode: ThemeMode, step: ForegroundOpacity): string {
  return rgba(mode, "foreground", tokens.opacity.foreground[step]);
}

/** Accent at a named opacity step, e.g. accent("light", "tint"). */
export function accent(mode: ThemeMode, step: AccentOpacity): string {
  return rgba(mode, "accent", tokens.opacity.accent[step]);
}
`;
}

function upper(p: Palette): Palette {
  return {
    accent: p.accent.toUpperCase() as Hex,
    accentText: p.accentText.toUpperCase() as Hex,
    background: p.background.toUpperCase() as Hex,
    foreground: p.foreground.toUpperCase() as Hex,
  };
}

// ───────────── Rust ─────────────

function f32(n: number): string {
  const s = num(n);
  return s.includes(".") ? s : `${s}.0`;
}

function rustStr(s: string): string {
  return JSON.stringify(s); // JSON escaping is valid Rust string-literal escaping for these inputs
}

export function toRust(t: Tokens): string {
  const pal = (name: string, p: Palette) => {
    const c = (hex: string) => {
      const [r, g, b] = hexToRgb(hex);
      return `Rgb { r: ${r}, g: ${g}, b: ${b} }`;
    };
    return `pub const ${name}: Palette = Palette {\n    accent: ${c(p.accent)},\n    accent_text: ${c(p.accentText)},\n    background: ${c(p.background)},\n    foreground: ${c(p.foreground)},\n};`;
  };
  const consts = (rec: Record<string, number>, ty: string, prefix = "") =>
    Object.entries(rec)
      .map(([k, v]) => `    pub const ${prefix}${screamingSnake(k)}: ${ty} = ${ty === "f32" ? f32(v) : v};`)
      .join("\n");
  const role = (r: FontRole) =>
    ({ serif: "FontRole::Serif", sans: "FontRole::Sans", mono: "FontRole::Mono" })[r];
  const style = (s: TextStyle) =>
    `TextStyle { font: ${role(s.font)}, size: ${f32(s.size)}, size_wide: ${s.sizeWide === undefined ? "None" : `Some(${f32(s.sizeWide)})`}, line_height: ${f32(s.lineHeight)}, tracking_em: ${f32(s.tracking)}, weight: ${s.weight}, uppercase: ${s.uppercase === true} }`;
  const styles = (scale: "app" | "brand") =>
    textEntries(t, scale)
      .map(([k, s]) => `    pub const ${screamingSnake(k)}: TextStyle = ${style(s)};`)
      .join("\n");
  const fontMod = (r: FontRole) => {
    const f = t.font[r];
    return `    pub mod ${r} {
        pub const FAMILY: &str = ${rustStr(f.family)};
        pub const FALLBACK: &[&str] = &[${f.fallback.map(rustStr).join(", ")}];
        pub const WEIGHTS: &[u16] = &[${f.weights.join(", ")}];
        /// (variant, file name in packages/tokens/fonts)
        pub const FILES: &[(&str, &str)] = &[${Object.entries(f.files)
          .map(([k, v]) => `(${rustStr(k)}, ${rustStr(v)})`)
          .join(", ")}];
    }`;
  };
  const easing = Object.entries(t.motion.easing)
    .map(([k, v]) => `        pub const ${screamingSnake(k)}: [f32; 4] = [${v.map(f32).join(", ")}];`)
    .join("\n");

  return `// ${GENERATED_HEADER}
// Rust owner: include with \`#[rustfmt::skip] mod generated; pub use generated::*;\` in crates/tokens/src/lib.rs
// (this file is the canonical layout; rustfmt must not reformat it, or tokens:build and cargo fmt disagree).
#![allow(dead_code)]

/// An sRGB colour with 8-bit channels.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct Rgb {
    pub r: u8,
    pub g: u8,
    pub b: u8,
}

impl Rgb {
    /// 0xRRGGBB
    pub const fn hex(self) -> u32 {
        ((self.r as u32) << 16) | ((self.g as u32) << 8) | (self.b as u32)
    }
    /// 0xRRGGBBAA with the given alpha in [0, 1].
    pub fn rgba_hex(self, alpha: f32) -> u32 {
        let a = (alpha.clamp(0.0, 1.0) * 255.0).round() as u32;
        (self.hex() << 8) | a
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Palette {
    pub accent: Rgb,
    /// Accent-coloured text and thin strokes (fills keep \`accent\`).
    pub accent_text: Rgb,
    pub background: Rgb,
    pub foreground: Rgb,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum FontRole {
    Serif,
    Sans,
    Mono,
}

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct TextStyle {
    pub font: FontRole,
    /// px
    pub size: f32,
    /// px, from 768px wide windows
    pub size_wide: Option<f32>,
    /// multiple of size
    pub line_height: f32,
    /// letter spacing in em
    pub tracking_em: f32,
    pub weight: u16,
    pub uppercase: bool,
}

${pal("LIGHT", t.color.light)}

${pal("DARK", t.color.dark)}

pub mod opacity {
    pub mod foreground {
${consts(t.opacity.foreground, "f32").replace(/^ {4}/gm, "        ")}
    }
    pub mod accent {
${consts(t.opacity.accent, "f32").replace(/^ {4}/gm, "        ")}
    }
}

/// 8px grid, values in px.
pub mod space {
    pub const BASE: f32 = ${f32(t.space.base)};
${consts(t.space.scale, "f32", "S")}
}

/// Corner radii in px.
pub mod radius {
${consts(t.radius, "f32")}
}

pub mod font {
${fontMod("serif")}
${fontMod("sans")}
${fontMod("mono")}
}

pub mod text {
    pub mod app {
        use super::super::{FontRole, TextStyle};
${styles("app").replace(/^ {4}/gm, "        ")}
    }
    pub mod brand {
        use super::super::{FontRole, TextStyle};
${styles("brand").replace(/^ {4}/gm, "        ")}
    }
}

pub mod motion {
    /// Durations in milliseconds. Honour reduced motion by using 0.
    pub mod duration {
${consts(t.motion.duration, "u64").replace(/^ {4}/gm, "        ")}
    }
    /// Cubic bezier control points (x1, y1, x2, y2).
    pub mod easing {
${easing}
    }
    pub mod orb {
        pub const BLUR: f32 = ${f32(t.motion.orb.blur)};
        pub const OPACITY: f32 = ${f32(t.motion.orb.opacity)};
        pub const FLOAT_SECONDS: &[f32] = &[${t.motion.orb.floatSeconds.map(f32).join(", ")}];
        pub const MORPH_SECONDS: &[f32] = &[${t.motion.orb.morphSeconds.map(f32).join(", ")}];
        pub const PULSE_SECONDS: f32 = ${f32(t.motion.orb.pulseSeconds)};
    }
}

/// Layout sizes in px.
pub mod layout {
${consts(t.layout, "f32")}
}

pub mod effect {
${consts(t.effect, "f32")}
}
`;
}
