//! Embeds the shared AI data so packaged desktop builds need no repository checkout:
//!
//! - `packages/ai/routing.json`, the only place model ids live (ARCHITECTURE §12.3). There is no
//!   fallback copy: a build without it fails here.
//! - the prompt pack in `packages/prompts` (§12.4): `manifest.json`, `shared/untrusted.md` and the
//!   plain files directly inside `features/<id>/` (eval fixtures are left out). The generated
//!   `prompt_pack.rs` lists them as `(relative path, include_str!(absolute path))`, and
//!   `PromptPack::embedded()` runs them through the same loader and checks as files on disk.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn fail(msg: &str) -> ! {
    panic!("akatsuki-ai build: {msg}")
}

fn rel(path: &Path, root: &Path) -> String {
    path.strip_prefix(root)
        .unwrap_or_else(|_| fail("path outside the prompt pack"))
        .to_string_lossy()
        .replace('\\', "/")
}

fn main() {
    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR"));
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets OUT_DIR"));
    let repo = manifest_dir.join("../..");

    let routing = repo.join("packages/ai/routing.json");
    println!("cargo:rerun-if-changed={}", routing.display());
    if !routing.is_file() {
        fail("packages/ai/routing.json is missing; crates/ai embeds it as the single routing table (§12.3)");
    }
    std::fs::copy(&routing, out_dir.join("routing.json")).unwrap_or_else(|e| fail(&format!("copy routing.json: {e}")));

    let pack = repo.join("packages/prompts");
    for watched in ["manifest.json", "shared", "features"] {
        println!("cargo:rerun-if-changed={}", pack.join(watched).display());
    }
    let mut files = vec![pack.join("manifest.json"), pack.join("shared/untrusted.md")];
    let features = std::fs::read_dir(pack.join("features")).unwrap_or_else(|e| {
        fail(&format!("packages/prompts/features is missing ({e}); crates/ai embeds the prompt pack"))
    });
    for dir in features.flatten().map(|e| e.path()).filter(|p| p.is_dir()) {
        let entries = std::fs::read_dir(&dir).unwrap_or_else(|e| fail(&format!("{}: {e}", dir.display())));
        files.extend(
            entries
                .flatten()
                .map(|e| e.path())
                .filter(|p| p.is_file() && p.extension().is_some_and(|x| x == "json" || x == "md")),
        );
    }
    files.sort();

    let mut src = String::from(
        "/// The prompt pack files, embedded at build time (generated by `build.rs`).\n\
         pub(crate) static EMBEDDED_PROMPT_FILES: &[(&str, &str)] = &[\n",
    );
    for file in &files {
        if !file.is_file() {
            fail(&format!("{} is missing", file.display()));
        }
        let abs = file.canonicalize().unwrap_or_else(|e| fail(&format!("{}: {e}", file.display())));
        let abs = abs.to_str().unwrap_or_else(|| fail("prompt pack paths must be UTF-8"));
        writeln!(src, "    ({:?}, include_str!({abs:?})),", rel(file, &pack)).expect("write to a String");
    }
    src.push_str("];\n");
    std::fs::write(out_dir.join("prompt_pack.rs"), src).unwrap_or_else(|e| fail(&format!("write prompt_pack.rs: {e}")));
}
